/**
 * The complete, explicit list of app strings that management may edit, grouped
 * into human-readable Hebrew sections.
 *
 * This is deliberately hand-curated rather than reflected off `R.string`:
 * reflection would also surface hundreds of framework/AndroidX strings (which
 * share the app resource package after merge) and there is no reliable runtime
 * signal to tell them apart from ours. An explicit list keeps the dashboard
 * clean, ordered, and — because every entry is an `R.string.*` reference — a
 * removed or renamed string becomes a compile error instead of a silent gap.
 *
 * Technician-only maintenance strings (`pc_authorize_*`) are intentionally
 * excluded: they live outside the main UI composition and must not be reworded.
 */
